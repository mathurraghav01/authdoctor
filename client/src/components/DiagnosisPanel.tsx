interface Props {
  result: DiagnosisResponse | null;
  loading: boolean;
  error: string | null;
  draft: RequestDraft;
  onLoadSample: () => void;
  onAsk: (prompt: string) => void;
}

const SOURCE_LABEL: Record<string, string> = {
  status: 'status',
  request: 'request',
  response: 'response',
  logs: 'logs',
  token: 'token',
  network: 'network',
};

export function engineLabel(result: DiagnosisResponse): string {
  if (result.engine === 'model') return result.model ? `Model · ${result.model}` : 'Model';
  if (result.engine === 'local-fallback') return 'Local fallback';
  return 'Local engine';
}

export function buildReport(result: DiagnosisResponse, draft: RequestDraft): string {
  const diagnosis = result.diagnosis;
  const lines: string[] = [
    `# ${diagnosis.title}`,
    '',
    `${draft.method} ${draft.url || '(no url)'} → ${draft.statusCode || 'no status'}`,
    '',
    diagnosis.summary,
    '',
    `**Most likely cause (${diagnosis.likelyCause.confidence} confidence):** ${diagnosis.likelyCause.cause}`,
    '',
    `**Confidence:** ${confidencePercent(diagnosis.confidence)}% · engine: ${engineLabel(result)}`,
    '',
    '## Verified from the supplied input',
    ...(diagnosis.verifiedFindings.length ? diagnosis.verifiedFindings.map((item) => `- ${item}`) : ['- Nothing could be verified.']),
    '',
    '## Likely explanations',
    ...diagnosis.likelyFindings.map((item) => `- ${item}`),
    '',
    '## Next steps',
    ...diagnosis.steps.map((step, index) => `${index + 1}. **${step.title}** — ${step.detail}${step.command ? `\n\n   \`\`\`\n   ${step.command}\n   \`\`\`` : ''}`),
    '',
    '## Suggested fix',
    diagnosis.fix.summary,
  ];

  if (diagnosis.fix.code) {
    lines.push('', `\`\`\`${diagnosis.fix.code.language}`, diagnosis.fix.code.content, '```');
  }
  if (diagnosis.curl) {
    lines.push('', '## Corrected curl', '```bash', diagnosis.curl, '```');
  }
  if (diagnosis.securityRisks.length) {
    lines.push('', '## Security notes', ...diagnosis.securityRisks.map((risk) => `- **${risk.severity}** ${risk.risk}: ${risk.detail}`));
  }
  if (diagnosis.alternatives.length) {
    lines.push('', '## Alternatives', ...diagnosis.alternatives.map((alt) => `- **${alt.likelihood}** ${alt.cause} — ${alt.note}`));
  }
  if (diagnosis.needsMoreInfo.length) {
    lines.push('', '## Missing information', ...diagnosis.needsMoreInfo.map((item) => `- ${item}`));
  }
  lines.push('', `_Generated by AuthDoctor (${engineLabel(result)}) at ${new Date(result.analyzedAt).toLocaleString()}. Review before applying; nothing here was executed or tested._`);
  return lines.join('\n');
}

export function buildAlanPrompt(result: DiagnosisResponse, draft: RequestDraft): string {
  return [
    'Act as a senior backend engineer helping me fix a failed API request.',
    'AuthDoctor already produced the diagnosis below from redacted material. Credentials are placeholders; do not ask me to paste real secrets.',
    'Do not claim to have executed or tested anything. Separate verified facts from assumptions, and tell me exactly what to check next.',
    '',
    `Request: ${draft.method} ${draft.url || '(no url)'} → ${draft.statusCode || 'no status'}`,
    `Engine: ${engineLabel(result)}`,
    '',
    '--- AUTHDOCTOR REPORT ---',
    buildReport(result, draft),
    '--- END REPORT ---',
    '',
    'Please review this diagnosis, challenge anything that looks wrong, and give me a concrete fix plan.',
  ].join('\n');
}

export function DiagnosisPanel({ result, loading, error, draft, onLoadSample, onAsk }: Props) {
  const [alanCopied, setAlanCopied] = useState(false);
  if (loading) return <DiagnosisSkeleton />;

  if (error) {
    return (
      <div className="p-5">
        <div className="rounded-xl border border-danger/25 bg-danger/[0.06] p-4">
          <div className="flex items-center gap-2 text-[13px] font-medium text-danger">
            <AlertTriangle size={15} />
            Diagnosis failed
          </div>
          <p className="mt-1.5 text-[12px] leading-relaxed text-fg-muted">{error}</p>
          <p className="mt-2 text-[11px] text-fg-dim">
            Your input was not stored. Check that the API server is running, then try again.
          </p>
        </div>
      </div>
    );
  }

  if (!result) {
    return (
      <div className="flex h-full flex-col justify-center p-6">
        <div className="mx-auto max-w-[300px] text-center">
          <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-xl border border-line bg-ink-800">
            <Fingerprint size={22} className="text-fg-dim" />
          </div>
          <h3 className="mt-4 text-[14px] font-semibold text-fg">No diagnosis yet</h3>
          <p className="mt-1.5 text-[12px] leading-relaxed text-fg-muted">
            Paste a failing request, or load a sample, then run the diagnosis. AuthDoctor separates what it can verify from what it is inferring.
          </p>
          <ul className="mt-4 space-y-2 text-left">
            {[
              'Status, headers, body, logs',
              'Root cause and evidence',
              'Fix, curl and next steps',
            ].map((item) => (
              <li key={item} className="flex items-center gap-2 text-[11.5px] text-fg-muted">
                <CheckCircle2 size={13} className="shrink-0 text-accent/70" />
                {item}
              </li>
            ))}
          </ul>
          <button type="button" onClick={onLoadSample} className="btn-ghost mt-5 w-full justify-center text-[12px]">
            <FlaskConical size={13} />
            Load the expired-token sample
          </button>
          <p className="mt-3 text-[10.5px] leading-relaxed text-fg-dim">
            No API key required in local mode.
          </p>
        </div>
      </div>
    );
  }

  const diagnosis = result.diagnosis;
  const verified = diagnosis.evidence.filter((item) => item.verified);
  const unverified = diagnosis.evidence.filter((item) => !item.verified);

  return (
    <div className="animate-fade-up">
      {result.engine !== 'model' && (
        <div className="mx-4 mt-4 rounded-lg border border-warn/20 bg-warn/[0.05] px-3 py-2 text-[11px] leading-relaxed text-warn/90">
          <span className="font-medium">
            {result.engine === 'local-fallback' ? 'Model unavailable — showing local analysis.' : 'Local mode — deterministic engine.'}
          </span>{' '}
          {result.engine === 'local-fallback'
            ? result.notes.find((note) => note.toLowerCase().includes('timed out') || note.toLowerCase().includes('failed') || note.toLowerCase().includes('validation')) ??
              'The configured model could not be used.'
            : 'No language model is connected. Verified findings are computed from your input; the rest is rule-based inference.'}
        </div>
      )}

      <div className="p-4">
        <div className="flex items-center justify-between gap-2">
          <div className="flex items-center gap-1.5">
            <StatusBadge code={draft.statusCode} />
            <span className={`chip ${CONFIDENCE_STYLES[diagnosis.likelyCause.confidence]}`}>
              {diagnosis.likelyCause.confidence} confidence
            </span>
          </div>
          <button
            type="button"
            onClick={() => copyText(buildReport(result, draft))}
            className="flex items-center gap-1 rounded px-1.5 py-1 text-[11px] text-fg-dim transition hover:bg-white/5 hover:text-fg"
            title="Copy the full report as Markdown"
          >
            <ArrowUpRight size={12} />
            Copy report
          </button>
          <button
            type="button"
            onClick={async () => {
              const ok = await copyText(buildAlanPrompt(result, draft));
              if (ok) {
                setAlanCopied(true);
                setTimeout(() => setAlanCopied(false), 1800);
              }
            }}
            className="flex shrink-0 items-center gap-1 rounded border border-accent/25 bg-accent-soft px-1.5 py-1 text-[10.5px] text-accent transition hover:border-accent/50"
            title="Copy a grounded, redacted prompt to continue this investigation in an Alan session"
          >
            <Sparkles size={11} />
            {alanCopied ? 'Copied' : 'Copy for Alan'}
          </button>
        </div>

        <h2 className="mt-3 text-balance text-[16px] font-semibold leading-snug tracking-tight text-fg">{diagnosis.title}</h2>
        <p className="mt-2 text-[12.5px] leading-relaxed text-fg-muted">{diagnosis.summary}</p>

        <div className="mt-4 rounded-lg border border-line bg-ink-800/60 p-3">
          <div className="flex items-center justify-between">
            <span className="label">Confidence</span>
            <span className="font-mono text-[11px] text-fg-muted">{confidencePercent(diagnosis.confidence)}%</span>
          </div>
          <div className="mt-1.5 h-1.5 overflow-hidden rounded-full bg-white/[0.06]">
            <div
              className={`h-full rounded-full transition-all duration-500 ${
                diagnosis.confidence >= 0.8 ? 'bg-ok' : diagnosis.confidence >= 0.6 ? 'bg-warn' : 'bg-fg-dim'
              }`}
              style={{ width: `${Math.max(6, confidencePercent(diagnosis.confidence))}%` }}
            />
          </div>
          <div className="mt-3 flex gap-2 border-t border-line/70 pt-3">
            <Lightbulb size={14} className="mt-0.5 shrink-0 text-accent" />
            <div>
              <p className="text-[12px] font-medium leading-snug text-fg">{diagnosis.likelyCause.cause}</p>
              <p className="mt-1 text-[11.5px] leading-relaxed text-fg-muted">{diagnosis.likelyCause.rationale}</p>
            </div>
          </div>
        </div>

        <Section icon={<BadgeCheck size={13} className="text-ok" />} title="Verified from your input" hint={`${verified.length}`}>
          {verified.length === 0 ? (
            <p className="text-[11.5px] leading-relaxed text-fg-dim">
              Nothing in the supplied material could be verified locally. Treat the diagnosis as a hypothesis.
            </p>
          ) : (
            <ul className="space-y-1.5">
              {verified.map((item, index) => (
                <li key={`${item.source}-${index}`} className="flex gap-2">
                  <span className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-ok" />
                  <div className="min-w-0">
                    <span className="mr-1.5 rounded bg-white/[0.04] px-1 py-0.5 font-mono text-[9.5px] uppercase tracking-wide text-fg-dim">
                      {SOURCE_LABEL[item.source]}
                    </span>
                    <span className="text-[11.5px] leading-relaxed text-fg-muted">{item.detail}</span>
                  </div>
                </li>
              ))}
            </ul>
          )}
        </Section>

        {unverified.length > 0 && (
          <Section icon={<CircleHelp size={13} className="text-warn" />} title="Inferred, not verified" hint={`${unverified.length}`}>
            <ul className="space-y-1.5">
              {unverified.map((item, index) => (
                <li key={`u-${index}`} className="flex gap-2">
                  <span className="mt-[7px] h-1 w-1 shrink-0 rounded-full border border-warn/70" />
                  <span className="text-[11.5px] leading-relaxed text-fg-muted">{item.detail}</span>
                </li>
              ))}
            </ul>
          </Section>
        )}

        <Section icon={<Wrench size={13} className="text-accent" />} title="Next steps">
          <ol className="space-y-2.5">
            {diagnosis.steps.map((step, index) => (
              <li key={step.title} className="flex gap-2.5">
                <span className="mt-0.5 flex h-[18px] w-[18px] shrink-0 items-center justify-center rounded border border-line-strong bg-ink-800 font-mono text-[9.5px] text-fg-muted">
                  {index + 1}
                </span>
                <div className="min-w-0 flex-1">
                  <p className="text-[12px] font-medium leading-snug text-fg">{step.title}</p>
                  <p className="mt-0.5 text-[11.5px] leading-relaxed text-fg-muted">{step.detail}</p>
                  {step.command && (
                    <div className="mt-1.5">
                      <CodeBlock code={step.command} language="bash" maxHeight="8rem" />
                    </div>
                  )}
                </div>
              </li>
            ))}
          </ol>
        </Section>

        <Section icon={<Sparkles size={13} className="text-ok" />} title="Suggested fix">
          <p className="text-[11.5px] leading-relaxed text-fg-muted">{diagnosis.fix.summary}</p>
          {diagnosis.fix.code && (
            <div className="mt-2">
              <CodeBlock code={diagnosis.fix.code.content} language={diagnosis.fix.code.language} maxHeight="15rem" />
            </div>
          )}
          {diagnosis.fix.notes.length > 0 && (
            <ul className="mt-2 space-y-1">
              {diagnosis.fix.notes.map((note) => (
                <li key={note} className="flex gap-1.5 text-[11px] leading-relaxed text-fg-dim">
                  <span className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-fg-dim" />
                  {note}
                </li>
              ))}
            </ul>
          )}
        </Section>

        {diagnosis.curl && (
          <Section icon={<Terminal size={13} className="text-info" />} title="Corrected request">
            <CodeBlock code={diagnosis.curl} language="bash" maxHeight="14rem" />
            <p className="mt-1.5 flex items-center gap-1 text-[10.5px] text-fg-dim">
              <ShieldCheck size={11} />
              Credentials are referenced as environment variables.
            </p>
          </Section>
        )}

        {diagnosis.securityRisks.length > 0 && (
          <Section icon={<ShieldCheck size={13} className="text-warn" />} title="Security notes">
            <ul className="space-y-2">
              {diagnosis.securityRisks.map((risk) => (
                <li key={risk.risk} className="rounded-lg border border-line bg-ink-800/40 px-2.5 py-2">
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-[11.5px] font-medium text-fg">{risk.risk}</span>
                    <span className={`chip py-0 text-[9.5px] uppercase ${CONFIDENCE_STYLES[risk.severity]}`}>{risk.severity}</span>
                  </div>
                  <p className="mt-1 text-[11px] leading-relaxed text-fg-muted">{risk.detail}</p>
                </li>
              ))}
            </ul>
          </Section>
        )}

        {diagnosis.alternatives.length > 0 && (
          <Collapsible title="Alternative explanations" count={diagnosis.alternatives.length}>
            <ul className="space-y-2">
              {diagnosis.alternatives.map((alt) => (
                <li key={alt.cause} className="flex items-start justify-between gap-2">
                  <div className="min-w-0">
                    <p className="text-[11.5px] font-medium text-fg-muted">{alt.cause}</p>
                    <p className="mt-0.5 text-[11px] leading-relaxed text-fg-dim">{alt.note}</p>
                  </div>
                  <span className={`chip shrink-0 py-0 text-[9.5px] uppercase ${CONFIDENCE_STYLES[alt.likelihood]}`}>{alt.likelihood}</span>
                </li>
              ))}
            </ul>
          </Collapsible>
        )}

        {diagnosis.needsMoreInfo.length > 0 && (
          <div className="mt-4 rounded-lg border border-dashed border-line-strong px-3 py-2.5">
            <div className="flex items-center gap-1.5 text-[11px] font-medium text-fg-muted">
              <FileQuestion size={12} />
              To raise confidence
            </div>
            <ul className="mt-1 space-y-1">
              {diagnosis.needsMoreInfo.map((item) => (
                <li key={item} className="text-[11px] leading-relaxed text-fg-dim">
                  {item}
                </li>
              ))}
            </ul>
          </div>
        )}

        <div className="mt-4 border-t border-line pt-3">
          <div className="flex flex-wrap gap-1.5">
            {['Generate a corrected curl', 'What should I check next?', 'Show the redaction report'].map((prompt) => (
              <button
                key={prompt}
                type="button"
                onClick={() => onAsk(prompt)}
                className="flex items-center gap-1 rounded-full border border-line bg-ink-800 px-2 py-1 text-[10.5px] text-fg-muted transition hover:border-accent/40 hover:text-fg"
              >
                <MessageSquare size={10} />
                {prompt}
              </button>
            ))}
          </div>

          <div className="mt-3 flex items-start gap-1.5 text-[10px] leading-relaxed text-fg-dim">
            <Clock size={11} className="mt-0.5 shrink-0" />
            <span>
              {result.redactions.total > 0
                ? `${result.redactions.total} secret${result.redactions.total === 1 ? '' : 's'} redacted (${result.redactions.kinds.join(', ')}). `
                : 'No secrets detected in this input. '}
              Generated {new Date(result.analyzedAt).toLocaleTimeString()} by {engineLabel(result)}. Review fixes before applying — AuthDoctor does not execute requests or verify fixes.
            </span>
          </div>
        </div>
      </div>
    </div>
  );
}

function Section({
  icon,
  title,
  hint,
  children,
}: {
  icon: ReactNode;
  title: string;
  hint?: string;
  children: ReactNode;
}) {
  return (
    <section className="mt-4 border-t border-line pt-3.5">
      <div className="mb-2 flex items-center gap-1.5">
        {icon}
        <h3 className="text-[11px] font-semibold uppercase tracking-[0.1em] text-fg-muted">{title}</h3>
        {hint && <span className="ml-auto font-mono text-[10px] text-fg-dim">{hint}</span>}
      </div>
      {children}
    </section>
  );
}

function Collapsible({ title, count, children }: { title: string; count: number; children: ReactNode }) {
  const [open, setOpen] = useState(false);
  return (
    <section className="mt-4 border-t border-line pt-3">
      <button type="button" onClick={() => setOpen((value) => !value)} className="flex w-full items-center gap-1.5 text-left">
        <ChevronDown size={12} className={`text-fg-dim transition ${open ? 'rotate-180' : ''}`} />
        <span className="text-[11px] font-semibold uppercase tracking-[0.1em] text-fg-muted">{title}</span>
        <span className="ml-auto font-mono text-[10px] text-fg-dim">{count}</span>
      </button>
      {open && <div className="mt-2 animate-fade-up">{children}</div>}
    </section>
  );
}

